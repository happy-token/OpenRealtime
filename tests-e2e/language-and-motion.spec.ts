import { expect, test } from "@playwright/test";

test("shows home-only controls, Star counts and a themed language list shared with settings", async ({ page }) => {
  await page.route("**/api/github-stars", route => route.fulfill({ json: { stars: 1250 } }));
  await page.goto("/conversation");
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  await expect(page.getByRole("link", { name: "GitHub", exact: true })).toContainText("1.3k");
  const homeLanguage = page.getByRole("combobox", { name: "Interface language", exact: true });
  await expect(homeLanguage).toHaveAttribute("data-value", "system");
  await homeLanguage.click();
  const list = page.getByRole("listbox", { name: "Interface language", exact: true });
  await expect(list).toBeVisible();
  expect(await list.evaluate(element => parseFloat(getComputedStyle(element).borderRadius))).toBeGreaterThan(0);
  await page.getByRole("option", { name: "简体中文", exact: true }).click();
  await page.goto("/settings");
  await expect(page.getByRole("heading", { name: "设置", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "GitHub", exact: true })).toHaveCount(0);
  const language = page.getByRole("combobox", { name: "界面语言", exact: true });
  await expect(language).toHaveAttribute("data-value", "zh-CN");
  await language.click();
  await page.getByRole("option", { name: "English", exact: true }).click();
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  await page.goto("/settings/appearance");
  await expect(page.getByRole("heading", { name: "Appearance", exact: true })).toBeVisible();
  await expect(page.getByRole("combobox", { name: "Interface language", exact: true })).toHaveAttribute("data-value", "en");
  await expect(page.getByRole("link", { name: "GitHub", exact: true })).toHaveCount(0);
});

test("preserves bilingual prompt edits and sends advanced selections to generation", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("openrealtime-language", "zh-CN"));
  const avatar = { avatar_id: "motion-i18n", display_name: "温柔陪伴", source_image_url: "/digital-human/avatar1.png", created_at: "2026-09-29T00:00:00Z", updated_at: "2026-09-29T00:00:00Z", deleted_at: null, actions: [], realtime_binding: null };
  await page.route("**/api/avatars/motion-i18n", route => route.fulfill({ json: { avatar } }));
  await page.route("**/api/liveportrait", route => route.fulfill({ json: { ready: true, templates: [] } }));
  await page.route("**/api/provider-key?**", route => route.fulfill({ json: { configured: true } }));
  await page.route("**/api/ltx/image-to-video", route => route.request().method() === "GET"
    ? route.fulfill({ json: { ready: true } })
    : route.fulfill({ status: 202, json: { task_id: "motion-test", state: "queueing" } }));
  await page.route("**/api/ltx/image-to-video/motion-test", route => route.fulfill({ json: { state: "queueing" } }));
  await page.goto("/avatars/create?task=action&avatar_id=motion-i18n");
  const studio = page.getByRole("dialog", { name: "生成动作", exact: true });
  await expect(studio).toBeVisible();
  const editor = studio.getByRole("textbox", { name: "动作提示词内容", exact: true });
  await expect(editor).toHaveValue(/全程不说话/);
  await editor.fill("中文底片修改，保持正面闭嘴");
  const promptLanguage = studio.getByRole("combobox", { name: "提示词语言", exact: true });
  await promptLanguage.click();
  await page.getByRole("option", { name: "English", exact: true }).click();
  await expect(editor).toHaveValue(/No speaking/);
  await editor.fill("English edited silent motion loop");
  await promptLanguage.click();
  await page.getByRole("option", { name: "简体中文", exact: true }).click();
  await expect(editor).toHaveValue("中文底片修改，保持正面闭嘴");
  await page.reload();
  await expect(editor).toHaveValue("中文底片修改，保持正面闭嘴");
  await promptLanguage.click();
  await page.getByRole("option", { name: "English", exact: true }).click();
  await expect(editor).toHaveValue("English edited silent motion loop");
  await studio.locator("summary").filter({ hasText: "高级选项" }).click();
  await studio.getByRole("combobox", { name: "MiniMax 时长", exact: true }).click();
  await studio.getByRole("option", { name: "10 秒", exact: true }).click();
  await studio.getByRole("combobox", { name: "MiniMax 分辨率", exact: true }).click();
  await studio.getByRole("option", { name: "2K", exact: true }).click();
  await studio.getByRole("combobox", { name: "MiniMax 画面比例", exact: true }).click();
  await studio.getByRole("option", { name: "9:16", exact: true }).click();
  await studio.getByRole("combobox", { name: "数字人形象角色", exact: true }).click();
  await studio.getByRole("option", { name: /仅首帧/ }).click();
  const submitted = page.waitForRequest(request => request.url().endsWith("/api/ltx/image-to-video") && request.method() === "POST");
  await studio.getByRole("button", { name: "生成", exact: true }).click();
  const request = await submitted;
  expect(request.postData()).toContain('name="duration"\r\n\r\n10');
  expect(request.postData()).toContain('name="resolution"\r\n\r\n2K');
  expect(request.postData()).toContain('name="ratio"\r\n\r\n9:16');
  expect(request.postData()).toContain('name="imageRole"\r\n\r\nfirst_frame');
  expect(request.postData()).toContain("English edited silent motion loop");
});

test("guests can open local preferences from the lower-left settings entry", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("openrealtime-language", "zh-CN"));
  await page.route("**/api/user/me", route => route.fulfill({ json: { signedIn: false } }));
  await page.goto("/conversation");
  await page.getByRole("button", { name: "固定展开侧边栏", exact: true }).click();
  await page.getByRole("button", { name: "设置", exact: true }).click();
  const menu = page.locator("#workspace-account-options");
  await expect(menu.getByRole("link", { name: "登录账户", exact: true })).toBeVisible();
  expect(await menu.evaluate(element => parseFloat(getComputedStyle(element).borderRadius))).toBeGreaterThan(0);
  const guestLanguage = menu.getByRole("combobox", { name: "界面语言", exact: true });
  const label = menu.getByText("语言", { exact: true });
  const labelBox = await label.boundingBox();
  expect(labelBox?.height).toBeLessThan(25);
  expect(await guestLanguage.evaluate(element => getComputedStyle(element).fontSize)).toBe("13px");
  await guestLanguage.click();
  await page.getByRole("option", { name: "English", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  await expect(menu.getByRole("link", { name: "Conversation preferences", exact: true })).toHaveCount(0);
  const menuBox = await menu.boundingBox();
  const sidebarBox = await page.locator("#workspace-navigation").boundingBox();
  expect(menuBox!.x + menuBox!.width).toBeLessThanOrEqual(sidebarBox!.x + sidebarBox!.width);
  await page.goto("/settings/advanced");
  await expect(page.getByRole("heading", { name: /^(Advanced configuration|高级配置)$/ })).toBeVisible();
  await page.locator('input[type="range"]').fill("37");
  await page.reload();
  await expect(page.locator('input[type="range"]')).toHaveValue("37");
});
